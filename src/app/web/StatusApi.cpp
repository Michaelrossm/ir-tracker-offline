  json += ",";
  json += "\"last_integrity_present\":";
  json += String(meter.lastIntegrityPresent ? "true" : "false");
  json += ",";
  json += "\"rx_gpio\":";
  json += String(config.rxPin);
  json += ",";
  json += "\"tx_gpio\":";
  json += String(config.txPin);
  json += ",";
  json += "\"ir_transmitting\":";
  json += String(irPulse.active ? "true" : "false");
